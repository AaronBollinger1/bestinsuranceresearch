/**
 * Generate the subject registry a thread can attach to.
 *
 * A thread is about something: a carrier, a coverage line, a question the
 * Record already answers. Letting a contributor type a free-text topic is how a
 * forum ends up with eleven spellings of the same insurer and no way to show a
 * reader everything said about one of them.
 *
 * So the subjects are exactly what the evidence layer publishes, and this script
 * copies them across as a checked-in file rather than the Commons reading the
 * Record's collections at request time. Three reasons, in order of how much they
 * cost when ignored:
 *
 * 1. The Commons is server-rendered. Reading the sibling directory at request
 *    time would mean the deployed bundle carrying a path into a project it does
 *    not deploy with.
 * 2. A generated file that is checked in has a diff. When a carrier record is
 *    renamed, the change shows up in review rather than silently re-pointing
 *    every thread attached to it.
 * 3. The two properties can be split into separate repositories later without
 *    this becoming the thing that stops it.
 *
 * `verify-threads.mjs` fails when this file is stale, so it cannot quietly rot -
 * which is the failure mode of every generated-and-committed file that nothing
 * checks.
 *
 * Run: node scripts/sync-subjects.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const RECORD = path.join(HERE, '..', '..', 'src', 'content');
const OUT = path.join(HERE, '..', 'src', 'lib', 'subjects.generated.ts');

/** Which of the Record's collections a thread may be about, and how each reads. */
const KINDS = [
	{ kind: 'company', dir: 'companies', route: '/companies', label: (d) => d.legalName },
	{ kind: 'coverage', dir: 'coverages', route: '/insurance', label: (d) => d.name },
	{ kind: 'question', dir: 'questions', route: '/questions', label: (d) => d.question },
];

export function buildSubjects(recordContent = RECORD) {
	const out = [];
	for (const { kind, dir, route, label } of KINDS) {
		const full = path.join(recordContent, dir);
		if (!fs.existsSync(full)) continue;
		for (const file of fs.readdirSync(full).sort()) {
			if (!file.endsWith('.json')) continue;
			const id = file.replace(/\.json$/, '');
			const data = JSON.parse(fs.readFileSync(path.join(full, file), 'utf8'));
			const name = label(data);
			if (!name) continue;
			out.push({ id: `${kind}:${id}`, kind, name, recordPath: `${route}/${id}` });
		}
	}
	/* Stable order, so a regenerated file has an empty diff unless something
	   actually changed. */
	out.sort((a, b) => a.id.localeCompare(b.id));
	return out;
}

/**
 * Emitted as a TypeScript module rather than JSON, and that is not a style
 * choice. Astro resolves a JSON import through Vite; the Node test runner needs
 * an import attribute for the same file, and the two disagree. A `.ts` module
 * is read identically by both, and it is typed, so a malformed subject is a
 * compile error rather than a runtime surprise.
 */
export function serialise(subjects) {
	return [
		'/* GENERATED by scripts/sync-subjects.mjs. Do not edit by hand.',
		' *',
		' * What a thread may be about: exactly what the evidence layer publishes.',
		' * Regenerate after adding a company, coverage or question record - the',
		' * suite fails the build when this file is stale.',
		' */',
		"import type { Subject } from './threads';",
		'',
		`export const GENERATED_SUBJECTS: Subject[] = ${JSON.stringify(subjects, null, '\t')};`,
		'',
	].join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
	const subjects = buildSubjects();
	fs.mkdirSync(path.dirname(OUT), { recursive: true });
	fs.writeFileSync(OUT, serialise(subjects));
	const byKind = subjects.reduce((n, s) => ({ ...n, [s.kind]: (n[s.kind] ?? 0) + 1 }), {});
	console.log(`${subjects.length} subjects written to ${path.relative(process.cwd(), OUT)}`);
	for (const [kind, count] of Object.entries(byKind)) console.log(`  ${kind}: ${count}`);
}
